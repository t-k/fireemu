/// Returns whether `ch` belongs to `\p{Ll}`, `\p{Lo}` or `\p{N}`.
#[must_use]
pub fn is_lowercase_other_letter_or_number(ch: char) -> bool {
    let scalar = u32::from(ch);
    LETTER_OR_NUMBER_RANGES
        .binary_search_by(|&(first, last)| {
            if last < scalar {
                std::cmp::Ordering::Less
            } else if first > scalar {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Returns whether `ch` is allowed in a label value: `\p{Ll}`, `\p{Lo}`, `\p{N}`, `_` or `-`.
#[must_use]
pub fn is_label_value_char(ch: char) -> bool {
    matches!(ch, '_' | '-') || is_lowercase_other_letter_or_number(ch)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn regex_members() -> impl Iterator<Item = (char, bool)> {
        let class = regex::Regex::new(r"^[\p{Ll}\p{Lo}\p{N}]$").expect("the class is valid");
        (0..=0x0010_FFFF_u32)
            .filter_map(char::from_u32)
            .map(move |ch| (ch, class.is_match(ch.encode_utf8(&mut [0; 4]))))
    }

    #[test]
    fn table_matches_the_regex_crate_for_every_scalar() {
        let mut checked = 0_u32;
        for (ch, expected) in regex_members() {
            assert_eq!(
                is_lowercase_other_letter_or_number(ch),
                expected,
                "U+{:04X}",
                u32::from(ch)
            );
            checked += 1;
        }
        // 0x110000 code points minus the 2048 surrogates.
        assert_eq!(checked, 0x0011_0000 - 0x800);
    }

    #[test]
    fn table_is_sorted_non_overlapping_and_merged() {
        for window in LETTER_OR_NUMBER_RANGES.windows(2) {
            assert!(window[0].1 + 1 < window[1].0, "{window:?}");
        }
        for &(first, last) in LETTER_OR_NUMBER_RANGES {
            assert!(first <= last, "{first:X}..{last:X}");
        }
    }

    #[test]
    fn underscore_and_hyphen_are_label_value_characters() {
        assert!(is_label_value_char('_'));
        assert!(is_label_value_char('-'));
        assert!(!is_label_value_char('.'));
        assert!(!is_label_value_char('A'));
        assert!(!is_label_value_char(' '));
    }

    #[test]
    fn boundary_scalars_are_classified() {
        for (ch, expected) in [
            ('\u{0}', false),
            ('/', false),
            ('0', true),
            ('9', true),
            ('a', true),
            ('z', true),
            ('A', false),
            ('\u{10FFFF}', false),
            ('\u{1FBF9}', true),
        ] {
            assert_eq!(is_lowercase_other_letter_or_number(ch), expected, "{ch:?}");
        }
    }

    #[test]
    #[ignore = "prints the range table; run manually to regenerate LETTER_OR_NUMBER_RANGES"]
    fn generate_table() {
        let mut ranges: Vec<(u32, u32)> = Vec::new();
        for (ch, member) in regex_members() {
            if !member {
                continue;
            }
            let scalar = u32::from(ch);
            match ranges.last_mut() {
                Some(last) if last.1 + 1 == scalar => last.1 = scalar,
                _ => ranges.push((scalar, scalar)),
            }
        }
        println!("static LETTER_OR_NUMBER_RANGES: &[(u32, u32)] = &[");
        for (first, last) in &ranges {
            println!("    (0x{first:04X}, 0x{last:04X}),");
        }
        println!("];");
    }
}
