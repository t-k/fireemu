//! Stable, escaped Markdown projections of validated inventory and existing ledgers.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use super::{rows, strings, text, Inventory, GOALS};
use serde_json::Value;

const NOTICE: &str = "<!-- Generated by compat-check --write-inventory. Do not edit. -->\n\n";
const TARGET: &str = "Target: this source tree; not a release attestation. No feature-level execution receipts have been accepted. Existing tests and historical matrices are references, not evidence that this tree or the npm release passed those cases.\n\n";

fn escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "&#124;")
        .replace(['\n', '\r'], " ")
        .replace('[', "&#91;")
        .replace(']', "&#93;")
        .replace('`', "&#96;")
        .replace('*', "&#42;")
        .replace('_', "&#95;")
        .replace('\\', "&#92;")
}

fn list(values: &[&str]) -> String {
    if values.is_empty() {
        "None mapped".to_owned()
    } else {
        values
            .iter()
            .map(|s| escape(s))
            .collect::<Vec<_>>()
            .join("; ")
    }
}

fn page(title: &str) -> String {
    format!("{NOTICE}# {title}\n\n{TARGET}")
}

fn sorted<'a>(v: &'a Value, key: &str) -> Vec<&'a Value> {
    let mut result: Vec<_> = rows(v, key).iter().collect();
    result.sort_by_key(|v| text(v, "id"));
    result
}

fn goal_page(goal: &str) -> &'static str {
    match goal {
        "AUTH-CORE" | "AUTH-IP-MAIN" => "authentication.md",
        "FS-STD-NATIVE" => "firestore-standard-native.md",
        "FS-ENT-NATIVE" => "firestore-enterprise-native.md",
        "FS-MONGODB" => "firestore-mongodb.md",
        "FS-ADMIN" => "firestore-admin.md",
        "FS-SDK" => "sdk-matrix.md",
        _ => "limitations.md",
    }
}

fn feature_status(feature: &Value, inv: &Inventory) -> &'static str {
    let caps = strings(feature, "capabilities");
    if caps.is_empty() {
        return "Unmapped, unverified";
    }
    if caps
        .iter()
        .all(|id| text(&inv.capabilities[id], "status") == "unsupported")
    {
        return "Unsupported";
    }
    if caps
        .iter()
        .all(|id| text(&inv.capabilities[id], "precision") == "strict-validation-only")
    {
        return "Validation only";
    }
    if caps
        .iter()
        .all(|id| text(&inv.capabilities[id], "precision") == "fixture-idp")
    {
        return "Mock/fixture only";
    }
    if caps.iter().any(|id| {
        ["strict-validation-only", "fixture-idp"]
            .contains(&text(&inv.capabilities[id], "precision"))
    }) {
        return "Partial, unverified";
    }
    if caps
        .iter()
        .all(|id| text(&inv.capabilities[id], "status") == "implemented")
    {
        "Implemented, unverified"
    } else {
        "Partial, unverified"
    }
}

pub(super) fn documents(inv: &Inventory) -> BTreeMap<String, String> {
    let mut docs = BTreeMap::new();
    docs.insert("README.md", overview(inv));
    docs.insert("sources.md", sources(inv));
    docs.insert("surfaces.md", surfaces(inv));
    docs.insert("requirements.md", requirements(inv));
    docs.insert("evidence-policy.md", policy());
    for (path, title) in [
        ("authentication.md", "Authentication"),
        (
            "firestore-standard-native.md",
            "Firestore Standard / Native",
        ),
        (
            "firestore-enterprise-native.md",
            "Firestore Enterprise / Native",
        ),
        (
            "firestore-mongodb.md",
            "Firestore with MongoDB compatibility",
        ),
        ("firestore-admin.md", "Firestore administration"),
        ("sdk-matrix.md", "SDK integration"),
        (
            "limitations.md",
            "Managed-service boundaries and limitations",
        ),
    ] {
        docs.insert(path, features(inv, path, title));
    }
    docs.into_iter()
        .map(|(path, contents)| (format!("docs/compatibility/{path}"), contents))
        .collect()
}

fn overview(inv: &Inventory) -> String {
    let mut out = page("Compatibility inventory");
    out.push_str("This inventory is **incomplete**. Its denominator is the explicitly listed seed set, not all Firebase documentation, APIs, inputs or execution schedules. Unknown and deferred items remain visible. A mapped implementation, a reviewed document and a successful run are separate facts.\n\n");
    out.push_str("The [expanded official-source acquisition and fresh candidate observations](acquisition.md) are tracked separately from this seed mapping. URL enumeration and candidate runs do not promote these feature labels.\n\n");
    writeln!(out, "Declared profiles: {}. These are scope dimensions, not a claim that each feature was tested in each profile.\n", list(&strings(&inv.meta, "profiles"))).unwrap();
    out.push_str("| Goal | Mapped feature groups | Details |\n| --- | --- | --- |\n");
    for goal in GOALS {
        let count = rows(&inv.features, "features")
            .iter()
            .filter(|f| text(f, "goal") == goal)
            .count();
        writeln!(out, "| {goal} | {count} | [Open]({}) |", goal_page(goal)).unwrap();
    }
    writeln!(out, "\nKnown source entries: {}. Reviewed sources: 0. Enumerated seed surfaces: {}. Accepted feature execution receipts: 0. None of these counts is a product compatibility percentage.\n", rows(&inv.sources, "sources").len(), rows(&inv.surfaces, "surfaces").len()).unwrap();
    out.push_str("[Source inventory](sources.md) · [API surface seed](surfaces.md) · [Requirement mappings and debt](requirements.md) · [Evidence policy](evidence-policy.md)\n\n## Existing authorities\n\nThe [compatibility contract](../../spec/compatibility/contract.json) owns the pinned official-emulator claims. The [capability manifest](../../crates/fireemu/src/capabilities.json) owns implementation declarations. The [requirement ledger](../../verification/requirements/requirements.json) owns requirement status and artifact references. These generated pages do not replace them.\n\nHistorical corpus comparisons: [Authentication](../../conformance/AUTH-PRODUCTION-MATRIX.md) and [Firestore](../../conformance/FIRESTORE-PRODUCTION-MATRIX.md). Read their artifact, source, profile and configuration identities; their row counts are not feature coverage and are not transferred to this source tree.\n\n## Open inventory work\n\n");
    for debt in strings(&inv.meta, "debt") {
        writeln!(out, "- {}", escape(debt)).unwrap();
    }
    out.push_str("\n## Updating\n\nEdit `spec/compatibility/inventory.json`, `sources/index.json`, `surfaces/index.json` and `features.json`. Link existing requirement and capability IDs; do not copy their statuses. Run:\n\n```sh\ncargo run -p compat-check -- --write-inventory\ncargo run -p compat-check\ncargo nextest run -p compat-check --profile pr\n```\n\nThe normal CI compatibility gate rejects malformed references and missing or edited generated pages. Schema 1 intentionally rejects execution receipts and completed source-review claims until their provenance can be checked. Release snapshots and upstream monitoring are not implemented yet.\n");
    out
}

fn sources(inv: &Inventory) -> String {
    let mut out = page("Official source seed inventory");
    out.push_str("Entries are discovery pointers. No retrieved body, content hash, extractor revision or completed review is claimed. Entry sections marked unknown retain the obligation to inspect headings, tables, warnings and SDK variants. URL uniqueness is checked; semantic duplicates and the complete upstream link graph still require review.\n\n| Source | Kind | Language | Review | Section classifications | Requirement mappings |\n| --- | --- | --- | --- | --- | --- |\n");
    for source in sorted(&inv.sources, "sources") {
        let sections: Vec<_> = rows(source, "sections")
            .iter()
            .map(|s| {
                format!(
                    "{}: {} ({})",
                    text(s, "id"),
                    text(s, "classification"),
                    text(s, "reason")
                )
            })
            .collect();
        let reqs: Vec<_> = rows(source, "sections")
            .iter()
            .flat_map(|s| strings(s, "requirements"))
            .collect();
        writeln!(
            out,
            "| [{}]({}) | {} | {} | {} | {} | {} |",
            escape(text(source, "id")),
            text(source, "url"),
            escape(text(source, "kind")),
            escape(text(source, "language")),
            escape(text(source, "review")),
            escape(&sections.join("; ")),
            list(&reqs)
        )
        .unwrap();
    }
    out
}

fn surfaces(inv: &Inventory) -> String {
    let mut out = page("API surface seed inventory");
    out.push_str("This is a representative seed, not complete Discovery/protobuf enumeration. A locator identifies a review target; it does not assert implementation. Method, field, oneof, enum and SDK transport coverage must be expanded independently.\n\n| Surface | Source | Locator | Kind / transport | Classification | Requirements / reason |\n| --- | --- | --- | --- | --- | --- |\n");
    for surface in sorted(&inv.surfaces, "surfaces") {
        writeln!(
            out,
            "| {} | {} | {} | {} / {} | {} | {}; {} |",
            escape(text(surface, "id")),
            escape(text(surface, "source")),
            escape(text(surface, "locator")),
            escape(text(surface, "kind")),
            escape(text(surface, "transport")),
            escape(text(surface, "classification")),
            list(&strings(surface, "requirements")),
            escape(text(surface, "reason"))
        )
        .unwrap();
    }
    out
}

fn features(inv: &Inventory, path: &str, title: &str) -> String {
    let mut out = page(title);
    out.push_str("Labels summarize only linked capability declarations. They do not establish that the entire feature or its applicable editions are implemented. Requirement counts refer to the existing ledger, which includes broad invariants as well as behavior requirements; they are not atomic specification coverage. Missing mappings are debt, not unsupported-product verdicts.\n\n");
    if path == "sdk-matrix.md" {
        out.push_str("Versions below come from the conformance package declarations. Dependency availability does not prove SDK execution or a tested platform. Lockfile binding and per-platform execution receipts remain open.\n\n| Package | Declared version | Execution |\n| --- | --- | --- |\n");
        for sdk in ["firebase", "firebase-admin", "firebase-tools"] {
            writeln!(
                out,
                "| {sdk} | {} | Not attested |",
                escape(inv.packages["dependencies"][sdk].as_str().unwrap_or(""))
            )
            .unwrap();
        }
        out.push('\n');
    }
    out.push_str("| Feature / applicability | Capability-derived label | Requirements: mapped / unfinished | Production | Official emulator | SDK | Known limitations |\n| --- | --- | --- | --- | --- | --- | --- |\n");
    let features: Vec<_> = sorted(&inv.features, "features")
        .into_iter()
        .filter(|f| goal_page(text(f, "goal")) == path)
        .collect();
    if features.is_empty() {
        out.push_str("| No feature mappings yet | Unmapped, unverified | 0 / unknown | Not attested | Not attested | Not attested | This goal remains in the inventory. |\n");
    }
    for f in &features {
        let reqs = strings(f, "requirements");
        let unfinished = rows(&inv.requirements, "requirements")
            .iter()
            .filter(|r| reqs.contains(&text(r, "id")) && text(r, "status") != "implemented")
            .count();
        let unfinished = if reqs.is_empty() {
            "unknown".to_owned()
        } else {
            unfinished.to_string()
        };
        let mut limitations: Vec<_> = strings(f, "limitations");
        for cap in strings(f, "capabilities") {
            limitations.extend(strings(&inv.capabilities[cap], "unimplemented"));
            limitations.extend(strings(&inv.capabilities[cap], "notes"));
        }
        writeln!(
            out,
            "| {}: {} / {} | {} | {} / {} | Not attested | Not attested | Not attested | {} |",
            escape(text(f, "id")),
            escape(text(f, "title")),
            escape(text(f, "appliesTo")),
            feature_status(f, inv),
            reqs.len(),
            unfinished,
            list(&limitations)
        )
        .unwrap();
    }
    out.push_str("\n## Traceability links\n\nAll links below are mappings. Test names and corpus paths must be reviewed for their actual assertions before a feature-level execution claim can be made.\n\n");
    for f in features {
        if text(f, "id") == "FS-AGGREGATIONS" {
            out.push_str("[Bounded compound-aggregation source review and execution evidence](aggregation-evidence.md). This separate slice does not promote the broad feature labels.\n\n");
        }
        if text(f, "id") == "AUTH-USERS" {
            out.push_str("[Bounded Auth basic candidate observations](auth-basic-evidence.md). These sanitized, unapproved observations do not promote the broad feature labels.\n\n");
            out.push_str("[Auth revision 2: signup-token controls and redacted provenance](auth-basic-v2.md). Twelve scoped cases; no automatic approval or broad Auth claim.\n\n");
        }
        writeln!(out, "### {}\n\nSources: {}. API surfaces: {}.\n\nRequirements: {}.\n\nContract claims: {}.\n", escape(text(f, "title")), list(&strings(f, "sources")), list(&strings(f, "surfaces")), list(&strings(f, "requirements")), list(&strings(f, "claims"))).unwrap();
        for cap in strings(f, "capabilities") {
            writeln!(
                out,
                "- {}: {} ([manifest](../../crates/fireemu/src/capabilities.json)).",
                escape(cap),
                escape(text(&inv.capabilities[cap], "status"))
            )
            .unwrap();
        }
        out.push('\n');
    }
    out.push_str("[Requirements and artifact references](requirements.md) · [Sources](sources.md) · [Surface inventory](surfaces.md) · [Evidence policy](evidence-policy.md)\n");
    out
}

fn requirements(inv: &Inventory) -> String {
    let mut out = page("Requirement mappings and coverage debt");
    out.push_str("This projection includes every existing ledger requirement, including requirements outside the Auth/Firestore seed scope. Unmapped means feature mapping work remains; it does not mean the requirement has no tests. Artifact references are copied for navigation and are validated by the existing traceability gate, not promoted to execution receipts here.\n\n| Requirement | Existing status | Features | Statement | Artifact references (not receipts) |\n| --- | --- | --- | --- | --- |\n");
    let mut mapped_caps = BTreeSet::new();
    for req in sorted(&inv.requirements, "requirements") {
        let features: Vec<_> = rows(&inv.features, "features")
            .iter()
            .filter(|f| strings(f, "requirements").contains(&text(req, "id")))
            .map(|f| text(f, "id"))
            .collect();
        let labels = if features.is_empty() {
            "Unmapped".to_owned()
        } else {
            list(&features)
        };
        writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            escape(text(req, "id")),
            escape(text(req, "status")),
            labels,
            escape(text(req, "statement")),
            escape(&req["artifacts"].to_string())
        )
        .unwrap();
    }
    for feature in rows(&inv.features, "features") {
        mapped_caps.extend(strings(feature, "capabilities"));
    }
    out.push_str("\n## Capabilities not mapped to feature rows\n\nThese declarations remain visible even when outside the seed scope. Their source statuses do not attest execution.\n\n| Capability | Existing status |\n| --- | --- |\n");
    if let Some(caps) = inv.capabilities.as_object() {
        for (id, cap) in caps {
            if !mapped_caps.contains(id.as_str()) {
                writeln!(out, "| {} | {} |", escape(id), escape(text(cap, "status"))).unwrap();
            }
        }
    }
    out
}

fn policy() -> String {
    let mut out = page("Evidence policy");
    out.push_str("## Independent axes\n\nImplementation status belongs to the capability manifest and requirement ledger. Source review belongs to a source snapshot and reviewed sections. Execution belongs to an exact run against an identified artifact, configuration, SDK and case set. Schema 1 supports discovery pointers and mappings only: all feature execution cells remain `Not attested`, and completed source review cannot be recorded. This is a deliberate fail-closed boundary, not a claim that historical runs do not exist.\n\n## Labels\n\n`Implemented, unverified` means every linked capability currently declares implemented; it does not cover unmapped behavior. `Partial, unverified` means the linked declarations are mixed or incomplete. `Unsupported` means all linked capabilities declare unsupported. `Unmapped, unverified` means no capability mapping has been reviewed. Notes preserve validation-only, fixture-only, external-service and known-divergence qualifications from the existing manifest.\n\n## Before accepting execution receipts\n\nA later schema must bind the tested binary/source digest, configuration readback (edition, API mode, concurrency mode, profile), SDK lock, corpus and comparator revision, exact case IDs, assertion results, execution timestamp and sanitized artifacts. Production live observations, official-emulator runs, recorded replay and SDK E2E are separate run kinds. Zero tests, all skipped, failed preconditions, unrecognized results and unknown cleanup cannot pass. Changed dependencies produce stale evidence, never automatic re-verification.\n\nRecording creates a candidate; comparison is read-only; acceptance needs a reviewable diff and explicit human decision. The current generator performs no network access and no production operations. It cannot accept expectations or publish a release claim.\n\n## Comparison obligations\n\nRetain missing/null and integer/double distinctions, ordered results, structured errors, timestamp relationships, persistent state and side effects. Fully consume pages and streams. Test normalizers independently. Rejected operations need post-state assertions; asynchronous outcomes may be inconclusive. Never expose credentials or raw tokens in evidence. Finite cases and bounded formal models do not prove all Firebase inputs or schedules equivalent.\n\n## Release separation\n\nThe source-tree pages do not describe the latest npm release. Historical corpus reports keep their original tested artifact/source identities. Release snapshots must eventually be generated from receipts for the distributed artifact and cannot use the later report commit as the tested binary identity. No `releases/<version>` snapshot exists in this schema.\n");
    out
}
