#!/usr/bin/env ruby

require "minitest/autorun"
require "tmpdir"
require "yaml"
require_relative "kani-ci-contract"

class KaniCiContractTest < Minitest::Test
  BASE_WORKFLOW = <<~YAML
    name: kani
    on:
      pull_request: {}
      push:
        branches: [main]
      workflow_dispatch: {}
    permissions:
      contents: read
    jobs:
      kani:
        runs-on: ubuntu-24.04
        timeout-minutes: 30
        permissions:
          contents: read
        steps:
          - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262
            with:
              persist-credentials: false
          - uses: dtolnay/rust-toolchain@b725eda525362e7cf34af9a7243cac1e3f01a7ec
            with:
              toolchain: 1.94.0
          - name: verify the pinned toolchain
            run: rustc --version | tee /dev/stderr | grep -q "$(sed -n 's/^channel = \\"\\(.*\\)\\"/\\1/p' rust-toolchain.toml)"
          - name: install Kani
            run: cargo install --locked kani-verifier --version 0.68.0
          - name: set up Kani
            run: cargo kani setup
          - name: run bounded proofs
            run: python3 verification/kani/run.py
  YAML
  # Frozen rows generated by the PICT model recorded with this contract's coverage evidence.
  GENERATED_PICT_ROWS = <<~TSV
    trigger\ttool\tproof
    correct\tcorrect\tcorrect
    missing_pr\tcorrect\tcorrect
    missing_main\tcorrect\tcorrect
    missing_manual\tcorrect\tcorrect
    filtered\tcorrect\tcorrect
    correct\tmissing_setup\tcorrect
    correct\tversion_drift\tcorrect
    correct\tcorrect\tmissing_command
    correct\tcorrect\tfailure_swallowed
    filtered\tmissing_setup\tfailure_swallowed
    filtered\tversion_drift\tmissing_command
    missing_manual\tmissing_setup\tmissing_command
    missing_pr\tmissing_setup\tfailure_swallowed
    missing_main\tmissing_setup\tmissing_command
    missing_pr\tversion_drift\tmissing_command
    missing_main\tversion_drift\tfailure_swallowed
    missing_manual\tversion_drift\tfailure_swallowed
  TSV

  def test_checked_in_workflow_satisfies_the_contract
    errors = KaniCiContract.validate_file(File.expand_path("../.github/workflows/kani.yml", __dir__))

    assert_empty errors
  end

  def test_yaml_mutations_that_remove_required_guards_are_rejected
    cases = {
      "missing pull request trigger" => ->(workflow) { workflow.fetch(true).delete("pull_request") },
      "missing main push trigger" => ->(workflow) { workflow.fetch(true).fetch("push").delete("branches") },
      "missing manual trigger" => ->(workflow) { workflow.fetch(true).delete("workflow_dispatch") },
      "filtered pull request trigger" => ->(workflow) { workflow.fetch(true)["pull_request"] = { "paths" => ["verification/**"] } },
      "missing setup" => ->(workflow) { workflow.dig("jobs", "kani", "steps").reject! { |step| step["run"] == "cargo kani setup" } },
      "version drift" => ->(workflow) { workflow.dig("jobs", "kani", "steps").find { |step| step["run"]&.include?("cargo install") }["run"] = "cargo install --locked kani-verifier --version 0.69.0" },
      "missing proof command" => ->(workflow) { workflow.dig("jobs", "kani", "steps").reject! { |step| step["run"] == "python3 verification/kani/run.py" } },
      "failure swallowing" => ->(workflow) { workflow.dig("jobs", "kani", "steps").find { |step| step["run"] == "python3 verification/kani/run.py" }["continue-on-error"] = true },
      "conditional proof skip" => ->(workflow) { workflow.dig("jobs", "kani", "steps").find { |step| step["run"] == "python3 verification/kani/run.py" }["if"] = "false" },
      "missing timeout" => ->(workflow) { workflow.dig("jobs", "kani").delete("timeout-minutes") },
      "writable token" => ->(workflow) { workflow["permissions"]["contents"] = "write" },
      "mutable action ref" => ->(workflow) { workflow.dig("jobs", "kani", "steps").first["uses"] = "actions/checkout@v4" },
      "persisted checkout token" => ->(workflow) { workflow.dig("jobs", "kani", "steps").first.dig("with")["persist-credentials"] = true }
    }

    cases.each do |label, mutate|
      workflow = YAML.safe_load(BASE_WORKFLOW, aliases: true)
      mutate.call(workflow)
      assert_rejected_yaml workflow, label
    end
  end

  def test_malformed_yaml_shapes_return_contract_errors
    mutations = [
      ->(workflow) { workflow[0] = "unexpected top-level key" },
      ->(workflow) { workflow.fetch(true)[0] = "unexpected event key" },
      ->(workflow) { workflow.dig("jobs", "kani")[0] = "unexpected job key" },
      ->(workflow) { workflow.dig("jobs", "kani", "steps").first["with"] = ["malformed checkout inputs"] },
      ->(workflow) { workflow.dig("jobs", "kani", "steps").first[0] = "unexpected step key" }
    ]

    mutations.each_with_index do |mutate, index|
      workflow = YAML.safe_load(BASE_WORKFLOW, aliases: true)
      mutate.call(workflow)
      refute_empty validate_yaml_fixture(workflow), "malformed YAML shape #{index + 1} must return a contract error"
    end
  end

  def test_generated_pict_rows_drive_the_workflow_contract
    table = ENV["KANI_CI_PICT_TABLE"] ? File.read(ENV.fetch("KANI_CI_PICT_TABLE")) : GENERATED_PICT_ROWS
    headers, rows = table.lines(chomp: true).map { |line| line.split("\t", -1) }.then { |all| [all.first, all.drop(1)] }
    rows.each_with_index do |row, index|
      factors = headers.zip(row).to_h
      workflow = YAML.safe_load(BASE_WORKFLOW, aliases: true)
      apply_trigger_factor(workflow, factors.fetch("trigger"))
      apply_tool_factor(workflow, factors.fetch("tool"))
      apply_proof_factor(workflow, factors.fetch("proof"))
      errors = validate_yaml_fixture(workflow)
      should_pass = factors.values.all? { |value| value == "correct" }
      assert_equal should_pass, errors.empty?, "generated PICT row #{index + 1}: #{factors.inspect}; errors: #{errors.join('; ')}"
    end
  end

  private

  def assert_rejected_yaml(workflow, label)
    errors = validate_yaml_fixture(workflow)
    refute_empty errors, "contract accepted #{label}"
  end

  def validate_yaml_fixture(workflow)
    Dir.mktmpdir("kani-ci-contract-") do |directory|
      fixture = File.join(directory, "workflow.yml")
      File.write(fixture, YAML.dump(workflow))
      KaniCiContract.validate_file(fixture)
    end
  end

  def apply_trigger_factor(workflow, factor)
    triggers = workflow.fetch(true)
    case factor
    when "correct" then nil
    when "missing_pr" then triggers.delete("pull_request")
    when "missing_main" then triggers.fetch("push")["branches"] = ["release"]
    when "missing_manual" then triggers.delete("workflow_dispatch")
    when "filtered" then triggers["pull_request"] = { "paths" => ["verification/**"] }
    else flunk "unknown trigger factor: #{factor}"
    end
  end

  def apply_tool_factor(workflow, factor)
    steps = workflow.dig("jobs", "kani", "steps")
    case factor
    when "correct" then nil
    when "missing_setup" then steps.reject! { |step| step["run"] == "cargo kani setup" }
    when "version_drift" then steps.find { |step| step["run"]&.include?("cargo install") }["run"] = "cargo install --locked kani-verifier --version 0.69.0"
    else flunk "unknown tool factor: #{factor}"
    end
  end

  def apply_proof_factor(workflow, factor)
    steps = workflow.dig("jobs", "kani", "steps")
    case factor
    when "correct" then nil
    when "missing_command" then steps.reject! { |step| step["run"] == "python3 verification/kani/run.py" }
    when "failure_swallowed" then steps.find { |step| step["run"] == "python3 verification/kani/run.py" }["continue-on-error"] = true
    else flunk "unknown proof factor: #{factor}"
    end
  end
end
