import { test } from "node:test";
import assert from "node:assert/strict";
import { createAuth } from "./breadth-auth.mjs";

test("creates, signs in, deletes and proves absence without exposing secrets", async () => {
  const rows = [],
    calls = [];
  const responses = [{ localId: "uid" }, { localId: "uid", idToken: "token-sentinel" }, {}, {}];
  const auth = createAuth({
    projectId: "demo",
    apiKey: "key-sentinel",
    email: "user@example.test",
    password: "password-sentinel",
    log: (row) => rows.push(row),
    fetchImpl: async (url, init) => {
      calls.push([url, init]);
      return { status: 200, text: async () => JSON.stringify(responses.shift()) };
    },
  });
  const created = await auth.create();
  assert.equal(auth.uid, "uid");
  const signed = await auth.signIn();
  assert.equal(created.outcome, "ok");
  assert.equal(signed.outcome, "ok");
  assert.equal(await auth.delete(), "ok");
  assert.equal(await auth.confirmGone(), true);
  assert.equal(calls.length, 4);
  assert.ok(calls[1][0].includes("key=key-sentinel"));
  const visible = JSON.stringify([rows, created, signed]);
  for (const secret of ["key-sentinel", "password-sentinel", "token-sentinel"])
    assert.ok(!visible.includes(secret));
  assert.equal(auth.idToken, "token-sentinel");
});

test("unknown answers stop further state changes and never expose secrets", async () => {
  const rows = [];
  let calls = 0;
  const auth = createAuth({
    projectId: "demo",
    apiKey: "key-sentinel",
    email: "user@example.test",
    password: "password-sentinel",
    log: (r) => rows.push(r),
    fetchImpl: async () => {
      calls++;
      throw Error("key-sentinel password-sentinel token-sentinel");
    },
  });
  assert.equal((await auth.create()).outcome, "unknown");
  await assert.rejects(auth.signIn(), (e) => !e.message.includes("sentinel"));
  assert.equal(await auth.delete(), "skipped");
  assert.equal(calls, 1);
  assert.ok(!JSON.stringify(rows).includes("sentinel"));
});

test("successful sign-in cannot be repeated", async () => {
  let calls = 0;
  const auth = createAuth({
    projectId: "demo",
    apiKey: "key",
    email: "user@example.test",
    password: "password",
    log: () => {},
    fetchImpl: async () => ({
      status: 200,
      text: async () =>
        JSON.stringify(++calls === 1 ? { localId: "uid" } : { localId: "uid", idToken: "id" }),
    }),
  });
  await auth.create();
  await auth.signIn();
  await assert.rejects(auth.signIn(), /sign in unavailable/);
  assert.equal(calls, 2);
});

// Rows generated by PICT with the required normal and unknown-answer seeds.
for (const [createAnswer, signInAnswer, signal] of [
  ["ok", "ok", "no"],
  ["ok", "unknown", "yes"],
  ["unknown", "ok", "yes"],
  ["unknown", "refused", "no"],
  ["refused", "refused", "yes"],
  ["ok", "refused", "no"],
  ["refused", "unknown", "no"],
  ["refused", "ok", "yes"],
  ["unknown", "unknown", "no"],
]) {
  test(`Auth cleanup preserves created ownership: ${createAnswer}/${signInAnswer}/signal=${signal}`, async () => {
    const stop = {};
    const calls = [];
    const auth = createAuth({
      projectId: "demo",
      apiKey: "test-key",
      email: "test@example.test",
      password: "test-password",
      stop,
      log: () => {},
      fetchImpl: async (url, init) => {
        calls.push([url, JSON.parse(init.body)]);
        const answer = url.endsWith("/accounts")
          ? createAnswer
          : url.includes("signInWithPassword")
            ? signInAnswer
            : "ok";
        return {
          status: answer === "ok" ? 200 : answer === "refused" ? 400 : 503,
          text: async () =>
            JSON.stringify(
              url.endsWith("/accounts")
                ? { localId: "owned" }
                : url.includes("signInWithPassword")
                  ? { localId: "owned", idToken: "test-id" }
                  : {},
            ),
        };
      },
    });
    await auth.create();
    if (createAnswer === "ok") await auth.signIn();
    if (signal === "yes") stop.requested = true;
    const deleted = await auth.delete();
    if (createAnswer === "ok") {
      assert.equal(deleted, "ok");
      assert.equal(await auth.confirmGone(), true);
      assert.deepEqual(calls.at(-2)[1], { localId: "owned" });
      assert.deepEqual(calls.at(-1)[1], { localId: ["owned"] });
    } else {
      assert.equal(deleted, "skipped");
      assert.equal(calls.length, 1);
    }
    await assert.rejects(auth.signIn());
  });
}
