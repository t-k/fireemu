// Generates content_types.rs and content-type-samples.json from the Content-Type lookup the pinned
// Hosting oracle uses: firebase-tools 15.28.2 -> superstatic -> mime-types
// (`mime.contentType(path.extname(file))`), and the compression middleware's `compressible`, each
// resolved from the package that requires it, so the mime-db versions are whatever those resolve.
//
//   node generate-content-types.mjs          rewrite both files
//   node generate-content-types.mjs --check  fail when either file is stale
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../../..');
const firebase = createRequire(join(repo, 'conformance/package.json'))('firebase-tools/package.json');
const fromFirebase = createRequire(createRequire(join(repo, 'conformance/package.json')).resolve('firebase-tools/package.json'));
const superstaticPath = fromFirebase.resolve('superstatic/package.json');
const fromSuperstatic = createRequire(superstaticPath);
const mime = fromSuperstatic('mime-types');
const fromMime = createRequire(fromSuperstatic.resolve('mime-types'));
const fromCompression = createRequire(fromSuperstatic.resolve('compression'));
const compressible = fromCompression('compressible');
const fromCompressible = createRequire(fromCompression.resolve('compressible'));
const versions = {
  'firebase-tools': firebase.version,
  superstatic: fromSuperstatic('superstatic/package.json').version,
  'mime-types': fromSuperstatic('mime-types/package.json').version,
  'mime-db (mime-types)': fromMime('mime-db/package.json').version,
  compression: fromSuperstatic('compression/package.json').version,
  compressible: fromCompression('compressible/package.json').version,
  'mime-db (compressible)': fromCompressible('mime-db/package.json').version,
};

// Exactly the call the responder makes for a file it serves.
const lookup = (file) => {
  const value = mime.contentType(posix.extname(file));
  return value === false ? null : { contentType: value, compressible: Boolean(compressible(value)) };
};

const extensions = Object.keys(mime.types).sort();
for (const ext of extensions) {
  if (ext !== ext.toLowerCase() || !/^[a-z0-9]/.test(ext) || /[^\x21-\x7e]/.test(ext)) {
    throw new Error(`extension ${JSON.stringify(ext)} is not a plain lower-case ASCII token`);
  }
}
const rows = extensions.map((ext) => {
  const found = lookup(`x.${ext}`);
  if (!found) throw new Error(`mime-types has no content type for its own extension ${ext}`);
  return [ext, found.contentType, found.compressible];
});

const quote = (text) => JSON.stringify(text);
const rust = `// @generated by generate-content-types.mjs; do not edit.
//
// The Content-Type of a served file in the pinned Hosting oracle: \`mime.contentType(path.extname(file))\`
// of the packages below, plus whether the compression middleware treats that type as compressible
// (and so adds \`Vary: Accept-Encoding\`). Keys are lower-case extensions without the dot, sorted.
${Object.entries(versions).map(([name, version]) => `// ${name} ${version}`).join('\n')}

/// \`(extension, content type, compressible)\`.
#[rustfmt::skip]
pub(super) static CONTENT_TYPES: &[(&str, &str, bool)] = &[
${rows.map(([ext, type, comp]) => `    (${quote(ext)}, ${quote(type)}, ${comp}),`).join('\n')}
];
`;

const edgeNames = [
  'index.html', 'a.HTML', 'a.Js', 'a.JSON', 'a.WOFF2', 'a.tar.gz', 'a.min.js', 'a.', 'a..', 'a', '.hidden', '.hidden.css',
  '..', '.', 'dir.v1/file', 'dir.v1/file.txt', 'dir.d/.x', 'a/b.c/d', 'a.unknownext', 'a.K', 'a.Kml',
  'a.İ', 'a. html', 'a.html ', 'x.sßs', 'a.js/', '...', '....', 'a...', '...x', '..x', '.x.', 'x/..', 'x/.', 'x.y/', 'a.b.c.js', '.js', '/.js', 'a/.js', '404.html', 'a.map', 'a.ts', 'a.ico', 'a.webmanifest',
];
const sampled = extensions.filter((_, i) => i % 7 === 0);
const names = [
  ...edgeNames,
  ...sampled.map((ext) => `f.${ext}`),
  ...sampled.map((ext) => `dir/F.${ext.toUpperCase()}`),
];
const samples = names.map((file) => {
  const found = lookup(file);
  return { file, extname: posix.extname(file), contentType: found?.contentType ?? null, compressible: found?.compressible ?? false };
});
const json = JSON.stringify({ versions, samples }, null, 2) + '\n';

const outputs = [
  [join(here, 'content_types.rs'), rust],
  [join(here, 'content-type-samples.json'), json],
];
if (process.argv[2] === '--check') {
  const stale = outputs.filter(([path, text]) => readFileSync(path, 'utf8') !== text).map(([path]) => path);
  if (stale.length) {
    console.error(`stale: ${stale.join(', ')}; run node generate-content-types.mjs`);
    process.exit(1);
  }
  console.log(`up to date: ${rows.length} extensions, ${samples.length} samples`);
} else {
  for (const [path, text] of outputs) writeFileSync(path, text);
  console.log(`wrote ${rows.length} extensions, ${samples.length} samples`);
}
