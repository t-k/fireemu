//! Digests for the `hashing` namespace (`crc32`, `crc32c`, `md5`, `sha256`), written out
//! here because the core crates carry no dependencies. Not used for anything that needs
//! collision resistance in the runtime itself; the rules only compare digests.

/// CRC-32 (IEEE 802.3, reflected, polynomial `0xEDB88320`).
#[must_use]
pub fn crc32(data: &[u8]) -> u32 {
    crc32_with(data, 0xEDB8_8320)
}

/// CRC-32C (Castagnoli, reflected, polynomial `0x82F63B78`).
#[must_use]
pub fn crc32c(data: &[u8]) -> u32 {
    crc32_with(data, 0x82F6_3B78)
}

fn crc32_with(data: &[u8], polynomial: u32) -> u32 {
    let mut crc = 0xFFFF_FFFF_u32;
    for &byte in data {
        crc ^= u32::from(byte);
        for _ in 0..8 {
            let mask = (crc & 1).wrapping_neg();
            crc = (crc >> 1) ^ (polynomial & mask);
        }
    }
    !crc
}

