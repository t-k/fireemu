const names = targets.map((t) => t.functionName);
const refused = { outcome: "refused", status: 401 };
const unknown = { outcome: "unknown", status: 0 };

/** One row of the model as a world of the flow fakes. */
function worldOf(row) {
  const v = Object.fromEntries(FACTORS.map((f, i) => [f, row[i]]));
  const fault = {};
  if (v.pre === "preflight") fault.preflightFails = true;
  if (v.pre === "present") fault.present = names[2];
  if (v.setup === "fails") fault.setupFails = true;
  const failAt = { first: 0, gen1last: 3, gen2first: 4, last: 7 }[v.deploy];
  if (failAt !== undefined) fault.failDeploy = names[failAt];
  if (v.deploy === "read2") fault.failRead = names[4];
  const answers = {
    refused8: { s8: refused },
    unknown1: { s1: unknown },
    unknown3: { s3: unknown },
    unknown9: { s9: unknown },
    refused2: { s2: refused },
  }[v.answers];
  if (answers) fault.answers = answers;
  if (v.logs === "incomplete") fault.logsIncomplete = true;
  if (v.silent === "gen1") fault.silent = new Set([names[1]]);
  if (v.silent === "gen2") fault.silent = new Set([names[6]]);
  if (v.cleanup === "fail1") fault.cleanupFails = names[1];
  if (v.cleanup === "fail2") fault.cleanupFails = names[6];
  if (v.cleanup === "throws") fault.cleanupThrows = names[2];
  if (v.inventory === "leftovers") {
    fault.inventory = {
      ok: false,
      deleted: [],
      residual: { triggers: ["t"] },
      incomplete: false,
      error: null,
    };
  }
  if (v.rtdb === "open") fault.rtdb = { closed: false, errors: ["e"], unresolved: [] };
  if (v.uploads === "open") fault.uploadsOpen = true;
  const signal = { predeploy: ["deploy", 0], deploy3: ["deploy", 3], write4: ["write", 3] }[
    v.signal
  ];
  return { fault, abortAt: signal ? signal[0] : null, abortIndex: signal ? signal[1] : 0 };
}

test("pairwise worlds of the run flow", async () => {
  for (const [index, row] of ROWS.entries()) {
    await checkWorld(worldOf(row), `row ${index}: ${row.join(" ")}`);
  }
});
