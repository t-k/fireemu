"""Writes crates/fireemu-core-database/src/rules/java_chars.rs from the character classes
JavaChars.java prints on the Java runtime the official emulator ran on.

javac JavaChars.java && java JavaChars > ../../crates/fireemu-core-database/tests/fixtures/java21-chars.txt
python3 java_chars.py ../../crates/fireemu-core-database/tests/fixtures/java21-chars.txt \
    ../../crates/fireemu-core-database/src/rules/java_chars.rs
"""
import sys

source, target = sys.argv[1], sys.argv[2]
lines = open(source, encoding="utf-8").read().splitlines()
version = lines[0].split()[1]
tables = {}
for line in lines[1:]:
    name, *ranges = line.split()
    # The case mappings are checked by a test against the fixture, not generated.
    if name.endswith("_map"):
        continue
    tables[name] = [tuple(int(x, 16) for x in r.split("-")) for r in ranges]

out = [
    f"//! Character classes of the Java runtime the official emulator ran on (Java {version}),",
    "//! for every code unit of the Basic Multilingual Plane. Generated by",
    "//! `tools/rtdb-regex-fuzz/java_chars.py` from `tests/fixtures/java21-chars.txt`, which",
    "//! `tools/rtdb-regex-fuzz/JavaChars.java` printed; do not edit by hand.",
    "",
]
for name, ranges in tables.items():
    const = name.upper()
    out.append(f"/// `{name}` ranges, inclusive.")
    out.append(f"const {const}: &[(u16, u16)] = &[")
    for lo, hi in ranges:
        out.append(f"    (0x{lo:04X}, 0x{hi:04X}),")
    out.append("];")
    out.append("")
out += [
    "fn in_ranges(ranges: &[(u16, u16)], c: char) -> bool {",
    "    let Ok(unit) = u16::try_from(u32::from(c)) else {",
    "        return false;",
    "    };",
    "    ranges",
    "        .binary_search_by(|&(lo, hi)| {",
    "            if hi < unit {",
    "                std::cmp::Ordering::Less",
    "            } else if lo > unit {",
    "                std::cmp::Ordering::Greater",
    "            } else {",
    "                std::cmp::Ordering::Equal",
    "            }",
    "        })",
    "        .is_ok()",
    "}",
    "",
    "/// `Character.digit(c, 10)`: the value of a decimal digit, which `Integer.parseInt` reads; each",
    "/// range is whole runs of the digits 0 to 9.",
    "pub(crate) fn decimal_digit(c: char) -> Option<u32> {",
    "    let unit = u16::try_from(u32::from(c)).ok()?;",
    "    let index = DECIMAL_DIGIT",
    "        .binary_search_by(|&(lo, hi)| {",
    "            if hi < unit {",
    "                std::cmp::Ordering::Less",
    "            } else if lo > unit {",
    "                std::cmp::Ordering::Greater",
    "            } else {",
    "                std::cmp::Ordering::Equal",
    "            }",
    "        })",
    "        .ok()?;",
    "    Some(u32::from(unit - DECIMAL_DIGIT[index].0) % 10)",
    "}",
    "",
    "/// `Character.isJavaIdentifierStart`; false outside the Basic Multilingual Plane, where the",
    "/// reader sees surrogates.",
    "pub(crate) fn is_identifier_start(c: char) -> bool {",
    "    in_ranges(IDENTIFIER_START, c)",
    "}",
    "",
    "/// `Character.isJavaIdentifierPart`; false outside the Basic Multilingual Plane.",
    "pub(crate) fn is_identifier_part(c: char) -> bool {",
    "    in_ranges(IDENTIFIER_PART, c)",
    "}",
    "",
    "/// `Character.getType(c) == SPACE_SEPARATOR`.",
    "pub(crate) fn is_space_separator(c: char) -> bool {",
    "    in_ranges(SPACE_SEPARATOR, c)",
    "}",
    "",
    "/// `Character.getType(c) == FORMAT`.",
    "pub(crate) fn is_format(c: char) -> bool {",
    "    in_ranges(FORMAT, c)",
    "}",
    "",
]
open(target, "w", encoding="utf-8").write("\n".join(out))
