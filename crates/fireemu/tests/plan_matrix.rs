fn write(dir: &Path, name: &str, text: &str) {
    let path = dir.join(name);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

struct Expected {
    project: (&'static str, &'static str),
    stale: Vec<&'static str>,
    allowed: Vec<&'static str>,
    overridden: Vec<&'static str>,
}

#[allow(clippy::too_many_lines)] // one scenario, written top to bottom
fn run_row(index: usize, row: (&str, &str, &str, &str, &str, &str)) {
    let (command, project, only, parent, policy, layout) = row;
    let dir = Scratch::new("plan-matrix", &index.to_string());
    let label = format!("{row:?}");

    // Files.
    let toml_dir = if layout == "canonical-other-dir" {
        "sub/"
    } else {
        ""
    };
    let mut toml = String::from("schemaVersion = 1\n");
    if project == "config-key" {
        toml.push_str("[daemon]\nauthProject = \"cfg-p\"\n");
    }
    match layout {
        "firebase-json" => {
            toml = format!("firebaseJson = \"firebase.json\"\n{toml}");
            // The reference key belongs above any table.
            write(
                &dir,
                "firebase.json",
                r#"{"firestore": {"rules": "fb.rules"}}"#,
            );
        }
        _ => toml.push_str("[rules]\nsource = \"c.rules\"\n"),
    }
    write(&dir, &format!("{toml_dir}fireemu.toml"), &toml);
    if matches!(project, "flag-alias" | "rc-default") {
        write(
            &dir,
            ".firebaserc",
            r#"{"projects": {"default": "rc-p", "al": "al-p"}}"#,
        );
    }

    // Arguments and environment.
    let mut args: Vec<String> = vec![command.into(), "--plan".into(), "--json".into()];
    if layout == "canonical-other-dir" {
        args.extend([
            "--config".into(),
            "sub/fireemu.toml".into(),
            "--no-config-discovery".into(),
        ]);
    }
    match project {
        "flag-alias" => args.extend(["--project".into(), "al".into()]),
        "flag-id" => args.extend(["--project".into(), "flag-p".into()]),
        _ => {}
    }
    match only {
        "firestore" => args.extend(["--only".into(), "firestore".into()]),
        "auth-storage" => args.extend(["--only".into(), "auth,storage".into()]),
        _ => {}
    }
    let mut env: Vec<(&str, &str)> = Vec::new();
    if matches!(parent, "pubsub" | "both") {
        env.push(("PUBSUB_EMULATOR_HOST", "localhost:8085"));
    }
    if matches!(parent, "firestore" | "both") {
        env.push(("FIRESTORE_EMULATOR_HOST", "localhost:1234"));
    }
    if policy != "warn" {
        args.push("--deny-inherited-emulator-env".into());
    }
    if policy == "deny-allow" {
        for (name, _) in &env {
            args.extend(["--allow-inherited-emulator-env".into(), (*name).into()]);
        }
    }
    if command == "exec" {
        args.extend(["--".into(), "true".into()]);
    }

    // Oracle.
    let project_expected = match project {
        "flag-alias" => ("al-p", "--project alias in .firebaserc"),
        "flag-id" => ("flag-p", "--project"),
        "rc-default" => ("rc-p", ".firebaserc default"),
        "config-key" => ("cfg-p", "daemon.authProject in fireemu.toml"),
        _ => ("demo-app", "built-in default"),
    };
    let mut expected = Expected {
        project: project_expected,
        stale: Vec::new(),
        allowed: Vec::new(),
        overridden: Vec::new(),
    };
    for (name, service) in [
        ("PUBSUB_EMULATOR_HOST", "pubsub"),
        ("FIRESTORE_EMULATOR_HOST", "firestore"),
    ] {
        if !env.iter().any(|(set, _)| *set == name) {
            continue;
        }
        let started = service == "firestore" && only != "auth-storage";
        if started {
            expected.overridden.push(name);
        } else if policy == "deny-allow" {
            expected.allowed.push(name);
        } else {
            expected.stale.push(name);
        }
    }
    let denied: Vec<&str> = if policy == "warn" {
        Vec::new()
    } else {
        expected.stale.clone()
    };

    let home = dir.join(".home");
    std::fs::create_dir_all(&home).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_fireemu"))
        .current_dir(&*dir)
        .args(&args)
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", &home)
        .envs(env.iter().copied())
        .stdin(Stdio::null())
        .output()
        .unwrap();
    let plan: Value = serde_json::from_slice(&output.stdout).unwrap_or_else(|e| {
        panic!(
            "{label}: not JSON ({e}): {}",
            String::from_utf8_lossy(&output.stderr)
        )
    });

    assert_eq!(plan["command"], command, "{label}");
    assert_eq!(plan["project"]["id"], expected.project.0, "{label}");
    assert_eq!(plan["project"]["source"], expected.project.1, "{label}");
    assert_eq!(plan["exec"].is_object(), command == "exec", "{label}");

    let inherited = plan["environment"]["inherited"].as_array().unwrap();
    let names_with = |disposition: &str| -> Vec<String> {
        let mut names: Vec<String> = inherited
            .iter()
            .filter(|entry| entry["disposition"] == disposition)
            .map(|entry| entry["name"].as_str().unwrap().to_owned())
            .collect();
        names.sort();
        names
    };
    let sorted = |names: &[&str]| -> Vec<String> {
        let mut names: Vec<String> = names.iter().map(|name| (*name).to_owned()).collect();
        names.sort();
        names
    };
    assert_eq!(
        names_with("kept-service-not-started"),
        sorted(&expected.stale),
        "{label}"
    );
    assert_eq!(
        names_with("kept-allowed"),
        sorted(&expected.allowed),
        "{label}"
    );
    assert_eq!(
        names_with("overridden"),
        sorted(&expected.overridden),
        "{label}"
    );
    let mut denied_in_plan: Vec<String> = plan["environment"]["denied"]
        .as_array()
        .unwrap()
        .iter()
        .map(|name| name.as_str().unwrap().to_owned())
        .collect();
    denied_in_plan.sort();
    assert_eq!(denied_in_plan, sorted(&denied), "{label}");
    assert_eq!(
        output.status.code(),
        Some(i32::from(!denied.is_empty())),
        "{label}"
    );
    // A warning names exactly the variables that stay stale and are not denied-as-error only.
    let warned = plan["warnings"].to_string();
    for name in &expected.stale {
        assert!(warned.contains(name), "{label}: no warning for {name}");
    }
    for name in expected.allowed.iter().chain(&expected.overridden) {
        assert!(
            !warned.contains(name),
            "{label}: unexpected warning for {name}"
        );
    }

    let rules = plan["paths"]
        .as_array()
        .unwrap()
        .iter()
        .find(|row| row["setting"] == "rules.source")
        .unwrap_or_else(|| panic!("{label}: no rules row in {}", plan["paths"]));
    let (base, written, warns) = match layout {
        "firebase-json" => ("firebase.json directory", "fb.rules", false),
        "canonical-other-dir" => ("working directory", "c.rules", true),
        _ => ("working directory", "c.rules", false),
    };
    assert_eq!(rules["base"], base, "{label}");
    assert_eq!(rules["written"], written, "{label}");
    assert_eq!(
        plan["warnings"]
            .to_string()
            .contains("resolves against the working directory"),
        warns,
        "{label}"
    );
}

#[test]
fn every_row_of_the_pairwise_table_resolves_as_the_oracle_says() {
    for (index, row) in ROWS.iter().enumerate() {
        run_row(index, *row);
    }
}
