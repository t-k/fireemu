// Oracle provenance: what exactly answered as "the official emulator" on this run.
//
// Nothing here is typed by hand. The version and integrity of `firebase-tools` come from the
// installed package and the lockfile, and the bundled emulator versions and checksums come
// from the CLI's own `downloadableEmulatorInfo.json`, so ORACLE.md cannot drift away from the
// tree that produced the fixtures.

