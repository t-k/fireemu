import { runInNewContext } from "node:vm";
import { expect, it } from "vitest";
import { querySdkSource, querySdkRequest } from "./querySdk";
import { compileQuery, defaultQuery } from "./firestoreQuery";

it("preserves integer precision, timestamps, null, bytes and limit wrappers for the SDK", () => {
  const compiled = {
    path: "firestore/v1/projects/p/databases/named/documents/parents/a:runQuery",
    body: {
      structuredQuery: {
        limit: 1,
        where: {
          fieldFilter: {
            value: {
              mapValue: {
                fields: {
                  n: { integerValue: "9223372036854775807" },
                  t: { timestampValue: "2026-01-01T00:00:00.123456789Z" },
                  nil: { nullValue: null },
                  bytes: { bytesValue: "YQ==" },
                },
              },
            },
          },
        },
      },
    },
  };
  const request = querySdkRequest(compiled);
  expect(request.parent).toBe("projects/p/databases/named/documents/parents/a");
  expect(request.structuredQuery.limit).toEqual({ value: 1 });
  expect(JSON.stringify(request)).toContain('"integerValue":"9223372036854775807"');
  expect(JSON.stringify(request)).toContain('"nanos":123456789');
  expect(JSON.stringify(request)).toContain('"nullValue":"NULL_VALUE"');
  expect(JSON.stringify(request)).toContain('"bytesValue":"YQ=="');
});
it("generates a bounded, local-only SDK script without credentials", () => {
  const compiled = compileQuery(
    "projects/demo-a/databases/(default)/documents",
    "cities",
    defaultQuery(),
  )._unsafeUnwrap();
  const source = querySdkSource(compiled);
  expect(source).toContain("FirestoreClient");
  expect(source).toContain("client.runQuery(request");
  expect(source).toContain("client.close()");
  expect(source).toContain("127.0.0.1");
  expect(source).toContain("timeout: 10000");
  expect(source).not.toContain("applicationDefault");
});

// Pairwise cases generated by PICT, including default and named/integer boundary seeds.
it.each([
  ["default", "absent", "absent", "50"],
  ["named", "integer", "descending", "1"],
  ["default", "integer", "ascending", "50"],
  ["default", "integer", "absent", "1"],
  ["named", "string", "absent", "50"],
  ["named", "absent", "descending", "1"],
  ["default", "string", "descending", "50"],
  ["named", "absent", "ascending", "1"],
  ["named", "string", "ascending", "1"],
])("preserves query parameters for %s/%s/%s/%s", (db, filter, order, limit) => {
  const draft = defaultQuery();
  draft.limit = limit!;
  if (filter !== "absent")
    draft.filters = [
      {
        field: "value",
        op: "EQUAL",
        type: filter as "string" | "integer",
        text: filter === "integer" ? "42" : "hello",
      },
    ];
  if (order !== "absent")
    draft.orders = [
      { field: "value", direction: order === "ascending" ? "ASCENDING" : "DESCENDING" },
    ];
  const compiled = compileQuery(
    `projects/demo-a/databases/${db === "default" ? "(default)" : "named"}/documents`,
    "cities",
    draft,
  )._unsafeUnwrap();
  const request = querySdkRequest(compiled);
  expect(request.parent).toContain(db === "default" ? "/(default)/" : "/named/");
  expect(request.structuredQuery.limit).toEqual({ value: Number(limit) });
  expect(request.structuredQuery.where).toEqual(compiled.body.structuredQuery.where);
  expect(request.structuredQuery.orderBy).toEqual(compiled.body.structuredQuery.orderBy);
});

it("executes the generated script without dropping special map keys and always closes the SDK", async () => {
  const request = JSON.parse(
    '{"path":"firestore/v1/projects/demo-a/databases/named/documents:runQuery","body":{"structuredQuery":{"limit":1,"where":{"fieldFilter":{"field":{"fieldPath":"map"},"op":"EQUAL","value":{"mapValue":{"fields":{"__proto__":{"stringValue":"kept"}}}}}}}}}',
  );
  let sent: unknown;
  let closed = false;
  const source = querySdkSource(request).replace("main().catch", "globalThis.done = main().catch");
  const context = {
    URL,
    process: { env: { FIRESTORE_EMULATOR_HOST: "127.0.0.1:8080" }, exitCode: 0 },
    console,
    done: undefined as Promise<void> | undefined,
    require: (name: string) =>
      name === "@grpc/grpc-js"
        ? { credentials: { createInsecure: () => ({}) } }
        : {
            v1: {
              FirestoreClient: class {
                async *runQuery(query: unknown) {
                  sent = query;
                  yield { done: true };
                }
                async close() {
                  closed = true;
                }
              },
            },
          },
  };
  runInNewContext(source, context);
  await context.done;
  expect(JSON.stringify(sent)).toContain('"__proto__":{"stringValue":"kept"}');
  expect(closed).toBe(true);
});
