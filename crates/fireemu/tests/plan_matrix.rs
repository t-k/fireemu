//! The resolver axes of `up --plan` / `exec --plan`, run over a pairwise (PICT) table.
//!
//! The model has six axes: the command, where the project ID comes from, the `--only`
//! selection, which emulator variables the parent environment carries, the inherited-variable
//! policy, and where the paths are written (the canonical configuration in the working
//! directory, the same file in another directory, or `firebase.json`). Every combination is
//! run through the binary and judged by an oracle written here from the documented rules, not
//! from the plan code.

